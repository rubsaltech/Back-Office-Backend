-- ============================================================================
-- V29 — Service jobs: linked service, base charge, consumed products, billing.
--
-- A service job is now created FROM a service in the catalog (service_id), and
-- snapshots that service's base charge (service_charge) at creation time.
-- During the repair, products consumed are recorded in service_job_products
-- (stock is drawn down immediately when added). When the job is billed at the
-- POS, an order is created (order_id) and the job is closed (billed_at).
-- ============================================================================

ALTER TABLE service_jobs
    ADD COLUMN service_id     BIGINT        REFERENCES services (id) ON DELETE SET NULL,
    ADD COLUMN service_charge NUMERIC(12,2) NOT NULL DEFAULT 0,
    ADD COLUMN order_id       BIGINT        REFERENCES orders (id) ON DELETE SET NULL,
    ADD COLUMN billed_at      TIMESTAMPTZ;

CREATE TABLE service_job_products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_job_id BIGINT        NOT NULL REFERENCES service_jobs (id) ON DELETE CASCADE,
    product_id     BIGINT,
    variant_id     BIGINT,
    product_name   VARCHAR(255),
    variant_name   VARCHAR(255),
    quantity       INT           NOT NULL DEFAULT 1,
    unit_price     NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ   NOT NULL,
    updated_at     TIMESTAMPTZ   NOT NULL
);
CREATE INDEX idx_service_job_products_job ON service_job_products (service_job_id);
