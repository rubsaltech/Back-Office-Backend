-- ============================================================================
-- V24 — Signup email-verification OTPs.
--
-- A pending signup: the account is NOT created until the emailed code is
-- verified. The name + password (hashed) are held here so the business can be
-- created on verification without the client re-sending them.
-- ============================================================================

CREATE TABLE signup_otps (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    name          VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    code_hash     VARCHAR(255) NOT NULL,
    expires_at    TIMESTAMPTZ  NOT NULL,
    used          BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_signup_otp_email ON signup_otps (email);
