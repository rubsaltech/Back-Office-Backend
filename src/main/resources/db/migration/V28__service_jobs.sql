-- ============================================================================
-- V28 — Service/repair job tracking.
--
-- A service_job is a repair/service ticket with a customer-facing token. Its
-- progress is an append-only list of service_job_updates (a timeline of stages
-- and notes); the job's current status mirrors the latest update.
-- ============================================================================

CREATE TABLE service_jobs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT       NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    store_id       BIGINT       NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    token          VARCHAR(20)  NOT NULL,
    customer_name  VARCHAR(255),
    customer_phone VARCHAR(50),
    device         VARCHAR(255),
    service_type   VARCHAR(255),
    status         VARCHAR(30)  NOT NULL DEFAULT 'RECEIVED',
    handler_name   VARCHAR(255),
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_service_job_token UNIQUE (business_id, token)
);
CREATE INDEX idx_service_jobs_store ON service_jobs (store_id, status);

CREATE TABLE service_job_updates (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_job_id BIGINT       NOT NULL REFERENCES service_jobs (id) ON DELETE CASCADE,
    status         VARCHAR(30)  NOT NULL,
    note           VARCHAR(1000),
    performed_by   VARCHAR(255),
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_service_job_updates_job ON service_job_updates (service_job_id, created_at);
