SELECT b.id,
       (SELECT s.id FROM stores s WHERE s.business_id = b.id ORDER BY s.created_at ASC LIMIT 1),
       '0821595192', 'Main Terminal', 'ACTIVE', now(), now()
FROM businesses b
ON CONFLICT (business_id, serial_number) DO NOTHING;
