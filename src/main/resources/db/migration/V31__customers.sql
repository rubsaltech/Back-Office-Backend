-- ============================================================================
-- V31 — Customers (per store) + a credit/debit ledger.
--
-- A customer belongs to a store (per-store scoping, like the catalog). Each
-- customer carries a cached `balance` kept in step with customer_transactions
-- (CREDIT / DEBIT rows). The ledger is wired for future POS use (orders on
-- account, payments received); for now customers start at a zero balance.
-- ============================================================================

CREATE TABLE customers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    store_id    BIGINT        NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    name        VARCHAR(255)  NOT NULL,
    email       VARCHAR(255),
    phone       VARCHAR(50),
    address     VARCHAR(500),
    city        VARCHAR(255),
    country     VARCHAR(255),
    note        VARCHAR(1000),
    status      VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    balance     NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL
);
CREATE INDEX idx_customers_store ON customers (store_id);

CREATE TABLE customer_transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    store_id    BIGINT        NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    customer_id BIGINT        NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    type        VARCHAR(10)   NOT NULL,          -- CREDIT | DEBIT
    amount      NUMERIC(12,2) NOT NULL DEFAULT 0,
    note        VARCHAR(500),
    order_id    BIGINT        REFERENCES orders (id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL
);
CREATE INDEX idx_customer_transactions_customer ON customer_transactions (customer_id, created_at);

-- ----------------------------------------------------------------------------
-- Back-fill the customer.* permission catalog for every EXISTING business.
-- (New businesses get these from DefaultPermissions at provisioning time.)
-- Owners derive authorities from all of their business's permissions.
-- ----------------------------------------------------------------------------
INSERT INTO permissions (business_id, permission_key, description, created_at, updated_at)
SELECT b.id, k.pkey, k.descr, now(), now()
FROM businesses b
CROSS JOIN (VALUES
    ('customer.view',   'View customers'),
    ('customer.create', 'Create customer'),
    ('customer.edit',   'Edit customer'),
    ('customer.delete', 'Delete customer')
) AS k(pkey, descr)
ON CONFLICT (business_id, permission_key) DO NOTHING;

-- Grant all customer.* perms to roles that manage the catalog (hold product.create).
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions pc  ON pc.business_id = r.business_id AND pc.permission_key = 'product.create'
JOIN role_permissions rpc ON rpc.role_id = r.id AND rpc.permission_id = pc.id
JOIN permissions p   ON p.business_id = r.business_id
                    AND p.permission_key IN ('customer.view', 'customer.create', 'customer.edit', 'customer.delete')
ON CONFLICT (role_id, permission_id) DO NOTHING;

-- Grant customer.view + customer.create to roles that can take orders (e.g. Cashier).
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions pc  ON pc.business_id = r.business_id AND pc.permission_key = 'order.create'
JOIN role_permissions rpc ON rpc.role_id = r.id AND rpc.permission_id = pc.id
JOIN permissions p   ON p.business_id = r.business_id
                    AND p.permission_key IN ('customer.view', 'customer.create')
ON CONFLICT (role_id, permission_id) DO NOTHING;
