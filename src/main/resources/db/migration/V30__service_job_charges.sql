-- ============================================================================
-- V30 — Ad-hoc extra charges on a service job.
--
-- Beyond the service's base charge, a repair may need extra labour/charges added
-- during tracking (e.g. "Extra diagnostics", "Water-damage cleaning"). These are
-- free-form title + amount lines; they land on the final POS receipt too.
-- ============================================================================

CREATE TABLE service_job_charges (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_job_id BIGINT        NOT NULL REFERENCES service_jobs (id) ON DELETE CASCADE,
    title          VARCHAR(255)  NOT NULL,
    amount         NUMERIC(12,2) NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ   NOT NULL,
    updated_at     TIMESTAMPTZ   NOT NULL
);
CREATE INDEX idx_service_job_charges_job ON service_job_charges (service_job_id);
