-- ============================================================================
-- V23 — Serialized units sold on an order line.
--
-- A permanent snapshot of which serialized unit(s) (IMEI / serial) were sold on
-- each order line. Unlike stock_units.order_item_id (a live pointer that is
-- cleared when an order is voided and the unit returns to stock), these rows are
-- never rewritten, so a completed order's invoice always shows its IMEIs.
-- ============================================================================

CREATE TABLE order_item_units (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT       NOT NULL REFERENCES order_items (id) ON DELETE CASCADE,
    stock_unit_id BIGINT       REFERENCES stock_units (id) ON DELETE SET NULL,
    serial        VARCHAR(120) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_order_item_units_item ON order_item_units (order_item_id);
