-- ============================================================================
-- V19 — Catalog variants (always-variant model).
--
-- The sellable unit is now the VARIANT, not the product. Price, barcode and
-- stock move from `products` onto `product_variants`. Every product gets at
-- least one variant; existing products are migrated to a single "Default"
-- variant that carries their current price & stock (no data loss).
-- ============================================================================

CREATE TABLE product_variants (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id         BIGINT        NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    store_id            BIGINT        NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    product_id          BIGINT        NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    variant_name        VARCHAR(255)  NOT NULL DEFAULT 'Default',
    attributes          JSONB         NOT NULL DEFAULT '{}',   -- {"Color":"Black","Storage":"128GB"}
    is_default          BOOLEAN       NOT NULL DEFAULT FALSE,
    sku                 VARCHAR(150)  NOT NULL,
    barcode             VARCHAR(150),
    price               NUMERIC(12,2) NOT NULL DEFAULT 0,
    purchased_price     NUMERIC(12,2) NOT NULL DEFAULT 0,
    tracking_type       VARCHAR(20)   NOT NULL DEFAULT 'NONE',  -- NONE | SERIAL
    on_hand             INTEGER       NOT NULL DEFAULT 0,       -- cached; kept in step with the ledger
    quantity_sold       INTEGER       NOT NULL DEFAULT 0,
    total_received      INTEGER       NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER       NOT NULL DEFAULT 5,
    status              VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at          TIMESTAMPTZ   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_variant_store_sku UNIQUE (store_id, sku)
);
CREATE INDEX idx_variants_product ON product_variants (product_id);
CREATE INDEX idx_variants_store   ON product_variants (store_id);

ALTER TABLE products ADD COLUMN has_variants BOOLEAN NOT NULL DEFAULT FALSE;

-- ---- Migrate every existing product into a single Default variant ----
INSERT INTO product_variants (business_id, store_id, product_id, variant_name, attributes, is_default,
    sku, barcode, price, purchased_price, tracking_type, on_hand, quantity_sold, total_received,
    low_stock_threshold, status, created_at, updated_at)
SELECT p.business_id, p.store_id, p.id, 'Default', '{}'::jsonb, TRUE,
    p.sku, p.barcode, p.price, p.purchased_price, 'NONE',
    p.available_qty, p.quantity_sold, p.total_qty, p.low_stock_threshold, p.status, now(), now()
FROM products p;

-- ---- Drop the columns that now live on the variant ----
ALTER TABLE products DROP COLUMN price;
ALTER TABLE products DROP COLUMN purchased_price;
ALTER TABLE products DROP COLUMN available_qty;
ALTER TABLE products DROP COLUMN quantity_sold;
ALTER TABLE products DROP COLUMN total_qty;
ALTER TABLE products DROP COLUMN low_stock_threshold;
