-- ============================================================================
-- V20 — Inventory as a movement ledger + serialized units.
--
-- `stock_movements` is an append-only ledger: every stock change (opening,
-- receive, sale, return, adjust) is one row with a signed quantity and the
-- resulting on-hand (balance_after). The variant's cached on_hand is kept in
-- step with it. `stock_units` tracks one row per serialized (IMEI) unit.
-- ============================================================================

CREATE TABLE stock_movements (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT       NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    store_id      BIGINT       NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    variant_id    BIGINT       NOT NULL REFERENCES product_variants (id) ON DELETE CASCADE,
    unit_id       BIGINT,                                      -- the serialized unit, when applicable
    movement_type VARCHAR(20)  NOT NULL,                       -- OPENING | RECEIVE | SALE | RETURN | ADJUST
    quantity      INTEGER      NOT NULL,                       -- signed: +receive, -sale
    balance_after INTEGER      NOT NULL,                       -- variant on_hand after this movement
    reason        VARCHAR(255),
    order_id      BIGINT       REFERENCES orders (id) ON DELETE SET NULL,
    performed_by  BIGINT,
    created_at    TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_movements_variant ON stock_movements (variant_id, created_at);
CREATE INDEX idx_movements_store   ON stock_movements (store_id, movement_type);

CREATE TABLE stock_units (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT       NOT NULL REFERENCES businesses (id) ON DELETE CASCADE,
    store_id      BIGINT       NOT NULL REFERENCES stores (id) ON DELETE CASCADE,
    product_id    BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    variant_id    BIGINT       NOT NULL REFERENCES product_variants (id) ON DELETE CASCADE,
    serial        VARCHAR(120) NOT NULL,                       -- IMEI / serial number
    status        VARCHAR(20)  NOT NULL DEFAULT 'IN_STOCK',    -- IN_STOCK | SOLD | RETURNED | DEFECTIVE
    order_id      BIGINT       REFERENCES orders (id) ON DELETE SET NULL,
    order_item_id BIGINT,
    received_at   TIMESTAMPTZ,
    sold_at       TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_unit_business_serial UNIQUE (business_id, serial)
);
CREATE INDEX idx_units_variant      ON stock_units (variant_id);
CREATE INDEX idx_units_store_status ON stock_units (store_id, status);

-- ---- Seed an OPENING-balance movement for every (migrated) variant ----
INSERT INTO stock_movements (business_id, store_id, variant_id, movement_type, quantity, balance_after, reason, created_at)
SELECT v.business_id, v.store_id, v.id, 'OPENING', v.on_hand, v.on_hand, 'Opening balance (migrated)', now()
FROM product_variants v;
